#!/usr/bin/env bash
set -euo pipefail

BLOCKLIST="/etc/guardrail/blocklist.txt"
HOSTS="/etc/hosts"
DNSMASQ_BLOCK="/etc/dnsmasq.d/guardrail-block.conf"
MARK_BEGIN="# GUARDRAIL-BLOCK-BEGIN"
MARK_END="# GUARDRAIL-BLOCK-END"

# Domains are blocked two ways:
#   - /etc/hosts entries (exact names, fast, defense in depth)
#   - a dnsmasq drop-in (address=/domain/0.0.0.0) which also covers every
#     subdomain — the thing /etc/hosts cannot do.
# Both are fed from the same blocklist; only the marked regions are ever touched.

domains() {
  grep -v -E '^\s*#|^\s*$' "$BLOCKLIST" || true
}

hosts_filter() {
  awk '
    /^# GUARDRAIL-BLOCK-BEGIN$/ {skip=1; next}
    /^# GUARDRAIL-BLOCK-END$/   {skip=0; next}
    !skip {print}
  '
}

hosts_on() {
  local body=""
  local d
  while IFS= read -r d; do
    # Sinkhole both families; 0.0.0.0 alone leaves AAAA lookups free to bypass.
    [ -n "$d" ] && body+="0.0.0.0 $d"$'\n'":: $d"$'\n'
  done < <(domains)
  {
    hosts_filter < "$HOSTS"
    printf '%s\n' "$MARK_BEGIN"
    printf '%s' "$body"
    echo "$MARK_END"
  } > "$HOSTS.tmp"
  mv "$HOSTS.tmp" "$HOSTS"
}

hosts_off() {
  local tmp
  tmp="$(mktemp)"
  hosts_filter < "$HOSTS" > "$tmp"
  cat "$tmp" > "$HOSTS"
  rm -f "$tmp"
}

dnsmasq_on() {
  {
    echo "# GUARDRAIL-BLOCK-BEGIN (generated by focus.sh — do not edit)"
    grep -v -E '^\s*#|^\s*$' "$BLOCKLIST" | while read -r d; do
      # Sinkhole A and AAAA; address=/d/0.0.0.0 answers IPv4 only and would let
      # AAAA queries fall through to the real upstream (and over NAT64/DNS64).
      printf 'address=/%s/0.0.0.0\n' "$d"
      printf 'address=/%s/::\n' "$d"
    done
    echo "# GUARDRAIL-BLOCK-END"
  } > "$DNSMASQ_BLOCK"
  dnsmasq_apply
}

dnsmasq_off() {
  rm -f "$DNSMASQ_BLOCK"
  dnsmasq_apply
}

dnsmasq_apply() {
  # Keep the real upstream list current, then restart (address= changes need a
  # restart; reload only clears the cache).
  if [ -x /usr/local/bin/guardrail-upstream ]; then
    /usr/local/bin/guardrail-upstream 2>/dev/null || true
  fi
  systemctl restart dnsmasq 2>/dev/null || true
}

case "${1:-}" in
  on)
    hosts_on
    dnsmasq_on
    ;;
  off)
    hosts_off
    dnsmasq_off
    ;;
  *)
    echo "usage: $0 on|off" >&2
    exit 2
    ;;
esac
